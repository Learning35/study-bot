# app.py
# The Flask part of my study bot. It saves decks and cards in a SQLite
# file (studybot.db) and the page talks to it through the /api/ routes.

import random
import sqlite3
import os
import time

import psycopg
from psycopg.rows import dict_row

from flask import Flask, g, jsonify, render_template, request

import quiz

app = Flask(__name__)
DB_FILE = os.environ.get("DATABASE_PATH", "studybot.db")
DATABASE_URL = os.environ.get("DATABASE_URL")

def execute_query(db, query, params=()):
    # PostgreSQL uses %s instead of ? for SQL values
    if DATABASE_URL:
        query = query.replace("?", "%s")

    return db.execute(query, params)


# ---------- database ----------

def get_db():
    # Open the database once per request and reuse it
    if "db" not in g:
        if DATABASE_URL:
            # Use PostgreSQL when deployed
            g.db = psycopg.connect(
                DATABASE_URL,
                row_factory=dict_row
            )
        else:
            # Use SQLite on my Mac
            g.db = sqlite3.connect(DB_FILE)
            g.db.row_factory = sqlite3.Row

    return g.db


@app.teardown_appcontext
def close_db(error):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def make_tables():
    # Use PostgreSQL when DATABASE_URL is available
    if DATABASE_URL:
        db = psycopg.connect(DATABASE_URL)

        db.execute("""
            CREATE TABLE IF NOT EXISTS decks (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS cards (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                deck_id INTEGER NOT NULL,
                term TEXT NOT NULL,
                definition TEXT NOT NULL,
                box INTEGER NOT NULL DEFAULT 0,
                due DOUBLE PRECISION NOT NULL DEFAULT 0,
                times_seen INTEGER NOT NULL DEFAULT 0,
                times_right INTEGER NOT NULL DEFAULT 0
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS stats (
                id INTEGER PRIMARY KEY CHECK (id = 1),
                asked INTEGER NOT NULL DEFAULT 0,
                correct INTEGER NOT NULL DEFAULT 0,
                streak INTEGER NOT NULL DEFAULT 0,
                best INTEGER NOT NULL DEFAULT 0
            )
        """)

        db.execute("""
            INSERT INTO stats (id)
            VALUES (1)
            ON CONFLICT (id) DO NOTHING
        """)

    else:
        # Keep using SQLite on your MacBook
        db = sqlite3.connect(DB_FILE)

        db.executescript("""
            CREATE TABLE IF NOT EXISTS decks (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS cards (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                deck_id INTEGER NOT NULL,
                term TEXT NOT NULL,
                definition TEXT NOT NULL,
                box INTEGER NOT NULL DEFAULT 0,
                due REAL NOT NULL DEFAULT 0,
                times_seen INTEGER NOT NULL DEFAULT 0,
                times_right INTEGER NOT NULL DEFAULT 0
            );

            CREATE TABLE IF NOT EXISTS stats (
                id INTEGER PRIMARY KEY CHECK (id = 1),
                asked INTEGER NOT NULL DEFAULT 0,
                correct INTEGER NOT NULL DEFAULT 0,
                streak INTEGER NOT NULL DEFAULT 0,
                best INTEGER NOT NULL DEFAULT 0
            );

            INSERT OR IGNORE INTO stats (id) VALUES (1);
        """)

    db.commit()
    db.close()

def get_stats(db):
    # Get the user's study statistics
    row = execute_query(
        db,
        "SELECT asked, correct, streak, best FROM stats WHERE id = 1"
    ).fetchone()

    return dict(row)


